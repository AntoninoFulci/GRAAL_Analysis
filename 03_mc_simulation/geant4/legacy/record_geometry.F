C     Record explicit application calls and delegate to unchanged GEANT3.
      SUBROUTINE AUDVOL(NAME,SHAPE,MED,P,NP,IV)
      CHARACTER*(*) NAME,SHAPE
      INTEGER MED,NP,IV
      REAL P(*)
      WRITE(77,100) 'V',NAME,SHAPE,MED,NP,(P(J),J=1,NP)
      CALL GSVOLU(NAME,SHAPE,MED,P,NP,IV)
  100 FORMAT(A,1X,A4,1X,A4,2I8,20(1X,E24.16))
      END

      SUBROUTINE AUDPOS(NAME,NC,MOTHER,X,Y,Z,IR,ONLY)
      CHARACTER*(*) NAME,MOTHER,ONLY
      INTEGER NC,IR
      REAL X,Y,Z
      WRITE(77,100) 'P',NAME,NC,MOTHER,X,Y,Z,IR,ONLY,0
      CALL GSPOS(NAME,NC,MOTHER,X,Y,Z,IR,ONLY)
  100 FORMAT(A,1X,A4,I8,1X,A4,3(1X,E24.16),I8,1X,A4,I8)
      END

      SUBROUTINE AUDPOP(NAME,NC,MOTHER,X,Y,Z,IR,ONLY,P,NP)
      CHARACTER*(*) NAME,MOTHER,ONLY
      INTEGER NC,IR,NP
      REAL X,Y,Z,P(*)
      WRITE(77,100) 'P',NAME,NC,MOTHER,X,Y,Z,IR,ONLY,NP,
     +             (P(J),J=1,NP)
      CALL GSPOSP(NAME,NC,MOTHER,X,Y,Z,IR,ONLY,P,NP)
  100 FORMAT(A,1X,A4,I8,1X,A4,3(1X,E24.16),I8,1X,A4,I8,
     +       20(1X,E24.16))
      END

      SUBROUTINE AUDROT(N,T1,P1,T2,P2,T3,P3)
      INTEGER N
      REAL T1,P1,T2,P2,T3,P3
      WRITE(77,100) 'R',N,T1,P1,T2,P2,T3,P3
      CALL GSROTM(N,T1,P1,T2,P2,T3,P3)
  100 FORMAT(A,I8,6(1X,E24.16))
      END

      SUBROUTINE AUDMAT(N,NAME,A,Z,D,R,AB,U,NU)
      INTEGER N,NU
      CHARACTER*(*) NAME
      REAL A,Z,D,R,AB,U(*)
      WRITE(77,100) 'M',N,NAME,A,Z,D
      CALL GSMATE(N,NAME,A,Z,D,R,AB,U,NU)
  100 FORMAT(A,I8,1X,A,3(1X,E24.16))
      END

      SUBROUTINE AUDMIX(N,NAME,A,Z,D,NL,W)
      INTEGER N,NL
      CHARACTER*(*) NAME
      REAL A(*),Z(*),D,W(*)
C     GSMIXT normalizes atomic counts into mass fractions in-place.
      CALL GSMIXT(N,NAME,A,Z,D,NL,W)
      WRITE(77,100) 'X',N,NAME,D,ABS(NL),
     +             (A(J),Z(J),W(J),J=1,ABS(NL))
  100 FORMAT(A,I8,1X,A,1X,E24.16,I8,60(1X,E24.16))
      END

      SUBROUTINE AUDMED(N,NAME,NMAT,IS,IF,FM,TM,DM,DE,EP,ST,U,NU)
      INTEGER N,NMAT,IS,IF,NU
      CHARACTER*(*) NAME
      REAL FM,TM,DM,DE,EP,ST,U(*)
      WRITE(77,100) 'T',N,NMAT,IS,IF,FM,TM,DM,DE,EP,ST
      CALL GSTMED(N,NAME,NMAT,IS,IF,FM,TM,DM,DE,EP,ST,U,NU)
  100 FORMAT(A,4I8,6(1X,E24.16))
      END
