C Test driver only. ORIGINAL PREAN kernels/includes copied byte-for-byte.
      PROGRAM CYLINDER_TRACKING_ORACLE
      INTEGER CASES,MODE
      READ(*,*) CASES
      DO I=1,CASES
        READ(*,*) MODE
        IF(MODE.EQ.2) THEN
          CALL ANGLE_CASE
        ELSE
          CALL CYLINDER_CASE(MODE)
        ENDIF
      ENDDO
      END

      SUBROUTINE ANGLE_CASE
      REAL A(3),B(3),THETA,PHI
      READ(*,*) A,B
      CALL TETA_PHI_TRACE_CALCUL(A(1),A(2),A(3),B(1),B(2),B(3),
     & THETA,PHI)
      WRITE(*,*) 1,TRANSFER(THETA,0),TRANSFER(PHI,0)
      END

      SUBROUTINE CYLINDER_CASE(MODE)
#include "parametres_cylindres.inc"
#include "geometrie_cylindres.inc"
#include "piedestaux_cylindres.inc"
#include "clusters_cylindres.inc"
#include "groupes_cylindres.inc"
#include "associations_cylindres.inc"
#include "traces_cylindres.inc"
#include "chamber.inc"
#include "lflag.inc"
      INTEGER MODE
      LDATA=.FALSE.
      LSIMUL=.TRUE.
      CALL INITIALISATION_CYLINDRES
      DO I=1,60
        PEDI1(I)=0
      ENDDO
      DO I=1,64
        PEDI2(I)=0
      ENDDO
      DO I=1,96
        PEDE1(I)=0
        PEDE2(I)=0
      ENDDO
      IF(MODE.EQ.1) THEN
        READ(*,*) A1,B1,C1,XBL1,DBC1,SEUIL1,SEUIL_CLUSTER1,
     &    SEUIL_MULTI1,SEUIL_CHARGE1
        READ(*,*) A2,B2,C2,XBL2,DBC2,SEUIL2,SEUIL_CLUSTER2,
     &    SEUIL_MULTI2,SEUIL_CHARGE2
        READ(*,*) A3,B3,C3,XBL3,DBC3,SEUIL3,SEUIL_CLUSTER3,
     &    SEUIL_MULTI3,SEUIL_CHARGE3
        READ(*,*) A4,B4,C4,XBL4,DBC4,SEUIL4,SEUIL_CLUSTER4,
     &    SEUIL_MULTI4,SEUIL_CHARGE4
        READ(*,*) DPHI1,ZMIN1,ZMAX1,DZ1_CUT
        READ(*,*) DPHI2,ZMIN2,ZMAX2,DZ2_CUT
        READ(*,*) DPHI_CUT
      ENDIF
      READ(*,*) MCCI
      IF(MCCI.GT.0) READ(*,*) (WCI(I),I=1,MCCI)
      READ(*,*) MCCE
      IF(MCCE.GT.0) READ(*,*) (WCE(I),I=1,MCCE)
      READ(*,*) MBCI1
      DO I=1,MBCI1
        READ(*,*) IBCI1(I),CBCI1(I)
      ENDDO
      READ(*,*) MBCI2
      DO I=1,MBCI2
        READ(*,*) IBCI2(I),CBCI2(I)
      ENDDO
      READ(*,*) MBCE1
      DO I=1,MBCE1
        READ(*,*) IBCE1(I),CBCE1(I)
      ENDDO
      READ(*,*) MBCE2
      DO I=1,MBCE2
        READ(*,*) IBCE2(I),CBCE2(I)
      ENDDO
      DO I=1,4
        CALL ANALYSE_CYLINDRE_CATHODE_2(I)
      ENDDO
      CALL ANALYSE_CYLINDRE_FILS_1(1)
      CALL ANALYSE_CYLINDRE_FILS_1(2)
      CALL ASSOCIATION_CYLINDRES(12)
      CALL ASSOCIATION_CYLINDRES(34)
      CALL ASSOCIATION_CHAMBRES
      WRITE(*,*) 0,STATUS_TRACES_CYL
      WRITE(*,*) TRANSFER(A1,0),TRANSFER(B1,0),TRANSFER(C1,0),
     & TRANSFER(XBL1,0)
      WRITE(*,*) TRANSFER(A2,0),TRANSFER(B2,0),TRANSFER(C2,0),
     & TRANSFER(XBL2,0)
      WRITE(*,*) TRANSFER(A3,0),TRANSFER(B3,0),TRANSFER(C3,0),
     & TRANSFER(XBL3,0)
      WRITE(*,*) TRANSFER(A4,0),TRANSFER(B4,0),TRANSFER(C4,0),
     & TRANSFER(XBL4,0)
      CALL PRINT_CLUSTERS(NCL1,IQ1,MCL1,BCL1,CCL1)
      CALL PRINT_CLUSTERS(NCL2,IQ2,MCL2,BCL2,CCL2)
      CALL PRINT_CLUSTERS(NCL3,IQ3,MCL3,BCL3,CCL3)
      CALL PRINT_CLUSTERS(NCL4,IQ4,MCL4,BCL4,CCL4)
      CALL PRINT_GROUPS(NCLW1,IQW1,MCLW1,PCLW1)
      CALL PRINT_GROUPS(NCLW2,IQW2,MCLW2,PCLW2)
      CALL PRINT_ASSOCIATIONS(NA1,IQA1,M1A1,M2A1,C1A1,C2A1,
     & DZA1,ZA1,PA1,IND_BAND1_CH1,IND_BAND2_CH1,IND_WIRE_CH1)
      CALL PRINT_ASSOCIATIONS(NA2,IQA2,M1A2,M2A2,C1A2,C2A2,
     & DZA2,ZA2,PA2,IND_BAND1_CH2,IND_BAND2_CH2,IND_WIRE_CH2)
      WRITE(*,*) NB_TRACES_CYL
      DO I=1,NB_TRACES_CYL
        WRITE(*,*) INDICE_TRACCIA_INT(I),INDICE_TRACCIA_EXT(I),
     & TRANSFER(DZ_TRACE_INT(I),0),TRANSFER(DZ_TRACE_EXT(I),0),
     & TRANSFER(X_TRACE_INT(I),0),TRANSFER(Y_TRACE_INT(I),0),
     & TRANSFER(Z_TRACE_INT(I),0),TRANSFER(X_TRACE_EXT(I),0),
     & TRANSFER(Y_TRACE_EXT(I),0),TRANSFER(Z_TRACE_EXT(I),0),
     & TRANSFER(DPHI_TRACE_CYL(I),0),TRANSFER(TETA_TRACE_CYL(I),0),
     & TRANSFER(PHI_TRACE_CYL(I),0),TRANSFER(Z_TRACE_CYL(I),0)
      ENDDO
      END

      SUBROUTINE PRINT_CLUSTERS(N,IQ,M,B,C)
      INTEGER N,IQ,M(20)
      REAL B(20),C(20)
      WRITE(*,*) N,IQ
      DO I=1,N
        WRITE(*,*) M(I),TRANSFER(B(I),0),TRANSFER(C(I),0)
      ENDDO
      END
      SUBROUTINE PRINT_GROUPS(N,IQ,M,P)
      INTEGER N,IQ,M(20)
      REAL P(20)
      WRITE(*,*) N,IQ
      DO I=1,N
        WRITE(*,*) M(I),TRANSFER(P(I),0)
      ENDDO
      END
      SUBROUTINE PRINT_ASSOCIATIONS(N,IQ,M1,M2,C1,C2,DZ,Z,P,
     & IND1,IND2,INDW)
      INTEGER N,IQ,M1(5),M2(5),IND1(5),IND2(5),INDW(5)
      REAL C1(5),C2(5),DZ(5),Z(5),P(5)
      WRITE(*,*) N,IQ
      DO I=1,N
        WRITE(*,*) M1(I),M2(I),TRANSFER(C1(I),0),TRANSFER(C2(I),0),
     & TRANSFER(DZ(I),0),TRANSFER(Z(I),0),TRANSFER(P(I),0),
     & IND1(I),IND2(I),INDW(I)
      ENDDO
      END
