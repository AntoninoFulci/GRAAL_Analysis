NAMES=('count_cluster_ca','metto_a_zero','ordino','cerca_max_rel','rearrange','associa','termostata','ordfever','contatto','distanza')

def generate():
    methods=[];manifest=[]
    for name in NAMES:
        p=ARCHIVE/'src'/f'{name}.c';text=p.read_text()
        start=re.search(r'(?:void|int) '+name+r'_?\([^;]*?\)\s*\{',text).start()
        method=text[start:]
        method=re.sub(r'\s*printf\([^;]*\);','',method)
        method=method.replace('bgoprean_.','bgo_prefix.').replace('bgo_prean_.','bgo_prefix.')
        # The machine branch only chooses a COMMON symbol. Both refer to the
        # same per-instance prefix, so select its original GRAAL_LINUX branch.
        method=re.sub(r'#if !defined\(GRAAL_LINUX\).*?#endif','',method,flags=re.S)
        method=method.replace('#if defined(GRAAL_LINUX)','').replace('#endif','')
        if name=='ordino':
            assert 'r = ((float)rand())/RAND_MAX;' in method
            method=method.replace('r = ((float)rand())/RAND_MAX;', 'r = draw_uniform();')
            method=method.replace('indici.klast += 1;', 'finite(ord[indici.klast].ecry);\n         indici.klast += 1;')
        if name=='count_cluster_ca':
            method=method.replace('  int iddu;', '  int iddu;\n  int previous_examined;')
            method=method.replace('  nox = rearrange();','  previous_examined=indici.iclexa;\n  nox = rearrange();')
            method=method.replace('  if(indici.iclexa < indici.klast) {','  if(indici.iclexa < indici.klast) {\n    if(indici.iclexa<=previous_examined) throw SourceDomain("CA growth made no progress");')
        if name=='termostata':method=method.replace('  for(k=0;k<indici.iclexa;k++){\n    if(esam[k].clclu == indice) {\n      esam[k].fever', '  finite(energia);\n  for(k=0;k<indici.iclexa;k++){\n    if(esam[k].clclu == indice) {\n      esam[k].fever')
        if name=='contatto':
            method=method.replace('  febbrona = uno.fever+due.fever;', '  febbrona = uno.fever+due.fever;\n  finite(febbrona);')
            method=method.replace('  if(iescon == 1 && due.fever > pcn_.rcnt*uno.fever) {', '  finite(pcn_.rcnt*uno.fever);\n  if(iescon == 1 && due.fever > pcn_.rcnt*uno.fever) {')
        if name=='distanza':
            for suffix in ('1','2'):
                method=method.replace(f'  xmed{suffix} /= avev{suffix};', f'  positive(avev{suffix});finite(xmed{suffix});finite(ymed{suffix});\n  xmed{suffix} /= avev{suffix};')
                method=method.replace(f'  ymed{suffix} /= avev{suffix};', f'  ymed{suffix} /= avev{suffix};\n  finite(xmed{suffix});finite(ymed{suffix});')
            method=method.replace('  dist = (float)sqrt((double)dist);', '  finite(dist);\n  dist = (float)sqrt((double)dist);')
            method=method.replace('    talfa = (su1-su2)/(esfera*dist);', '    positive(esfera*dist);\n    talfa = (su1-su2)/(esfera*dist);')
            method=method.replace('  if(talfa > pcn_.tde) {', '  finite(talfa);\n  if(talfa > pcn_.tde) {\n    finite(su1+su2);')
        for name_math in ('abs','sqrt','fabs'):
            method=re.sub(r'\b'+name_math+r'\(', 'std::'+name_math+'(',method)
        methods.append(method)
        manifest.append(dict(path=str(p.relative_to(ROOT)),sha256=hashlib.sha256(p.read_bytes()).hexdigest()))
